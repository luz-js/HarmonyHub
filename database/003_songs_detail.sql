ALTER TABLE "Song"
  ADD COLUMN IF NOT EXISTS "album" TEXT,
  ADD COLUMN IF NOT EXISTS "year" INTEGER,
  ADD COLUMN IF NOT EXISTS "genre" TEXT,
  ADD COLUMN IF NOT EXISTS "timeSignature" TEXT,
  ADD COLUMN IF NOT EXISTS "language" TEXT,
  ADD COLUMN IF NOT EXISTS "isFavorite" BOOLEAN NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS "coverUrl" TEXT,
  ADD COLUMN IF NOT EXISTS "youtubeUrl" TEXT;

CREATE TABLE IF NOT EXISTS "SongTrack" (
  "id" TEXT PRIMARY KEY,
  "songId" TEXT NOT NULL,
  "name" TEXT NOT NULL,
  "durationSec" INTEGER,
  "storageKey" TEXT,
  "url" TEXT,
  "isPrimary" BOOLEAN NOT NULL DEFAULT false,
  "sortOrder" INTEGER NOT NULL DEFAULT 0,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "SongTrack_songId_fkey"
    FOREIGN KEY ("songId") REFERENCES "Song"("id") ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS "SongTrack_songId_sortOrder_idx"
  ON "SongTrack"("songId", "sortOrder");
